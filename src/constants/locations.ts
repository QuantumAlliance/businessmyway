export const getCityOptions = (countryIso?: string, stateIso?: string): { value: string; label: string }[] => {
  const dynamicCities =
    countryIso && stateIso
      ? City.getCitiesOfState(countryIso, stateIso).map((c) => ({
          value: c.name,
          label: c.name,
        }))
      : [];

  const baseCities =
    !countryIso || countryIso === "GB"
      ? UK_CITIES.map((name) => ({
          value: name,
          label: name,
        }))
      : [];

  const map = new Map<string, { value: string; label: string }>();
  [...dynamicCities, ...baseCities].forEach((item) => {
    const key = item.value.toLowerCase().trim();
    if (!map.has(key)) {
      map.set(key, item);
    }
  });

  return Array.from(map.values()).sort((a, b) => a.label.localeCompare(b.label));
};
